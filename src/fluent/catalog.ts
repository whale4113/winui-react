const namespaces: Record<string, string> = {
  MicaBackdrop: "Microsoft.UI.Xaml.Media",
  AcrylicBrush: "Microsoft.UI.Xaml.Media",
  RevealBrush: "Microsoft.UI.Xaml.Media",
  Hyperlink: "Microsoft.UI.Xaml.Documents",
};
export const catalog = categories.slice(1).flatMap((c) =>
  c.items.map((name) => {
    const hint = special[name] || name;
    const candidates = resources.resources.filter(
      (r) => r.variant === "standard",
    );
    const resource =
      candidates.find((r) => r.name === hint) ||
      candidates.find((r) => r.file.endsWith(hint + "_themeresources.xaml")) ||
      candidates.find((r) => r.file.includes("/" + hint + "/"));
    return {
      name,
      category: c.name,
      zh: c.zh,
      source:
        sourceOverrides[name] ||
        resource?.file ||
        "microsoft-ui-xaml/dxaml/xcp/dxaml/themes/generic.xaml",
      metrics: resource?.metrics || {},
      hasThemeResource: Boolean(resource),
      namespace: namespaces[name] || "Microsoft.UI.Xaml.Controls",
      description: descriptions[name] || `${name} 控件示例。`,
    };
  }),
);
export type Entry = (typeof catalog)[number];

